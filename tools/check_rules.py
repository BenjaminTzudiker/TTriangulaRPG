"""Checks for the rules notes in rules/, and a compiler that joins them into one file.

    python3 tools/check_rules.py                    links resolve, titles match, index reaches every note
    python3 tools/check_rules.py --changelog BASE   if rules/ changed since BASE, CHANGELOG.md did too
    python3 tools/check_rules.py --compile OUT.md   the whole packet as one plain Markdown file
    python3 tools/check_rules.py --nav              rewrite the reading-order links from the index

The reading order lives in one place, the Contents of the index note. --nav derives the rest
from it: each note's up/prev/next properties, and the Full Packet note that embeds every note.
The plain check fails when those are out of date.

Standard library only. The layout these checks enforce is described in rules/README.md.
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RULES = ROOT / "rules"
INDEX = "Playtest Packet"
CHANGELOG = "CHANGELOG"
META = {"README", CHANGELOG}  # notes about the rules, not rule notes
SKIP_MARK = "[no changelog]"
FULL = "Full Packet"  # generated by --nav: every note embedded, in reading order
NAV_KEYS = ("up", "prev", "next")
# Notes that only repeat rules. Each ## section names its sources; a note with no sections
# names them once.
RESTATES = {"Quick Reference", "Sample Character"}

# [[Note]], [[Note#Heading]], [[Note|alias]], [[#Heading]], ![[Note]]; "\|" inside tables.
LINK = re.compile(r"(!?)\[\[([^\]#|\\]*)(?:#([^\]|\\]+))?(?:\\?\|([^\]]*))?\]\]")
HEADING = re.compile(r"^(#+)\s+(.+?)\s*$", re.M)
FENCE = re.compile(r"^```.*?^```", re.M | re.S)
INLINE_CODE = re.compile(r"`[^`\n]*`")
FRONTMATTER = re.compile(r"\A---\n(.*?)\n?---\n", re.S)


def load() -> tuple[dict[str, Path], list[str]]:
    notes: dict[str, Path] = {}
    problems = []
    for path in sorted(RULES.rglob("*.md")):
        if any(part.startswith(".") for part in path.relative_to(RULES).parts):
            continue
        if path.stem in notes:
            problems.append(f"two notes named {path.stem!r}: {notes[path.stem]} and {path}")
        notes[path.stem] = path
    return notes, problems


def body(text: str) -> str:
    """A note without its properties (frontmatter)."""
    m = FRONTMATTER.match(text)
    return text[m.end():] if m else text


def nav_of(text: str) -> dict[str, str]:
    """A note's up/prev/next properties."""
    m = FRONTMATTER.match(text)
    found = re.findall(r'^(up|prev|next): "\[\[([^\]]+)\]\]"$', m.group(1) if m else "", re.M)
    return dict(found)


def prose(text: str) -> str:
    """Text with code removed, so examples of link syntax aren't read as links."""
    return INLINE_CODE.sub("", FENCE.sub("", text))


def headings(text: str) -> set[str]:
    return {m.group(2) for m in HEADING.finditer(prose(text))}


def links(text: str) -> list[tuple[bool, str, str | None, str | None]]:
    return [(m.group(1) == "!", m.group(2).strip(), m.group(3), m.group(4))
            for m in LINK.finditer(prose(text))]


def contents_links(index_text: str) -> list[str]:
    """Notes listed under the index's Contents heading, in order."""
    part = body(index_text).split("\n## Contents\n", 1)
    if len(part) != 2:
        sys.exit(f"{INDEX}.md has no '## Contents' section")
    return [target for _, target, _, _ in links(part[1]) if target]


def embedded_in(texts: dict[str, str]) -> dict[str, str]:
    """Each embedded note, mapped to the note that embeds it (Full Packet aside)."""
    return {t: name for name, text in texts.items() if name != FULL
            for embed, t, _, _ in links(body(text)) if embed and t in texts}


def reading_order(texts: dict[str, str]) -> list[tuple[str, list[str]]]:
    """The index's Contents as (part, notes) in order, leaving out embedded notes, which are
    read inside the note that embeds them."""
    contents = body(texts[INDEX]).split("\n## Contents\n", 1)[1]
    skip = set(embedded_in(texts)) | META | {INDEX, FULL}
    parts, seen = [], set()
    for block in re.split(r"^### ", contents, flags=re.M)[1:]:
        title, _, rest = block.partition("\n")
        names = [t for _, t, _, _ in links(rest) if t in texts and t not in skip | seen]
        seen.update(names)
        if names:
            parts.append((title.strip(), names))
    return parts


def expected_nav(texts: dict[str, str]) -> dict[str, dict[str, str]]:
    """up/prev/next for every note: a chain through the reading order, starting at the index.
    An embedded note links up to the note that embeds it."""
    chain = [INDEX] + [name for _, names in reading_order(texts) for name in names]
    nav: dict[str, dict[str, str]] = {name: {} for name in texts}
    for i, name in enumerate(chain):
        if i:
            nav[name] |= {"up": INDEX, "prev": chain[i - 1]}
        if i + 1 < len(chain):
            nav[name]["next"] = chain[i + 1]
    for child, parent in embedded_in(texts).items():
        nav[child] = {"up": parent}
    nav[FULL] = {"up": INDEX}
    for name in META:
        nav[name] = {}
    return nav


def full_packet(texts: dict[str, str]) -> str:
    lines = [f"# {FULL}", "",
             "%% Generated by tools/check_rules.py --nav from the Contents of the index. "
             "Edit the notes and the index, not this. %%", "",
             "The whole packet in reading order, for reading straight through. Each section is "
             "the note itself, embedded: open it to edit.", ""]
    for part, names in reading_order(texts):
        lines += [f"# {part}", ""]
        for name in names:
            lines += [f"![[{name}]]", ""]
    return "\n".join(lines).rstrip() + "\n"


def with_nav(text: str, nav: dict[str, str]) -> str:
    """The note with its up/prev/next properties set to `nav`, other properties kept."""
    m = FRONTMATTER.match(text)
    other = [line for line in (m.group(1).splitlines() if m else [])
             if not re.match(r"^(up|prev|next):", line)]
    props = [f'{key}: "[[{nav[key]}]]"' for key in NAV_KEYS if key in nav] + other
    rest = body(text)
    return f"---\n{chr(10).join(props)}\n---\n{rest}" if props else rest


def write_nav() -> None:
    notes, problems = load()
    if problems:
        sys.exit("\n".join(problems))
    texts = {name: path.read_text() for name, path in notes.items()}
    texts.setdefault(FULL, "")
    texts[FULL] = full_packet(texts)
    paths = notes | {FULL: RULES / f"{FULL}.md"}
    nav = expected_nav(texts)
    changed = 0
    for name, text in texts.items():
        new = with_nav(text, nav.get(name, {}))
        if not paths[name].exists() or paths[name].read_text() != new:
            paths[name].write_text(new)
            changed += 1
    print(f"reading order: {changed} notes updated")


def check() -> list[str]:
    notes, problems = load()
    texts = {name: path.read_text() for name, path in notes.items()}
    heads = {name: headings(text) for name, text in texts.items()}

    for name, text in texts.items():
        if name not in META and not body(text).startswith(f"# {name}\n"):
            problems.append(f"{name}: first line should be '# {name}'")
        for _, target, heading, _ in links(text):
            note = target or name
            if note not in notes:
                problems.append(f"{name}: link to missing note [[{target}]]")
            elif heading and heading not in heads[note]:
                problems.append(f"{name}: link to missing heading [[{target}#{heading}]]")

    for name in RESTATES & set(texts):
        sections = re.split(r"^## ", texts[name], flags=re.M)[1:]
        if not sections and not re.search(r"^\*Restates .*\[\[", texts[name], re.M):
            problems.append(f"{name}: no '*Restates [[...]]*' line")
        for section in sections:
            title = section.split("\n", 1)[0].strip()
            if not re.search(r"^\*Restates .*\[\[", section, re.M):
                problems.append(f"{name}: section {title!r} has no '*Restates [[...]]*' line")

    if INDEX not in texts:
        return problems + [f"no index note {INDEX}.md"]
    reached: set[str] = set()
    todo = [t for t in contents_links(texts[INDEX]) if t in notes]
    while todo:
        name = todo.pop()
        if name in reached:
            continue
        reached.add(name)
        todo += [t for embed, t, _, _ in links(texts[name]) if embed and t in notes]
    for name in sorted(set(notes) - reached - META - {INDEX, FULL}):
        problems.append(f"{name}: not reached from the Contents of {INDEX}")

    nav = expected_nav(texts)
    stale = sorted(name for name, text in texts.items() if nav_of(text) != nav.get(name, {}))
    if FULL not in texts or body(texts[FULL]) != full_packet(texts):
        stale = sorted(set(stale) | {FULL})
    if stale:
        problems.append(f"reading order out of date in {', '.join(stale[:4])}"
                        f"{f' and {len(stale) - 4} more' if len(stale) > 4 else ''}: "
                        "run python3 tools/check_rules.py --nav")
    return problems


def check_changelog(base: str) -> list[str]:
    def git(*args: str) -> str:
        return subprocess.run(["git", *args], cwd=ROOT, check=True, capture_output=True,
                              text=True).stdout

    changed = [f for f in git("diff", "--name-only", "-z", base, "HEAD", "--", "rules/").split("\0") if f]
    if not changed or f"rules/{CHANGELOG}.md" in changed:
        return []
    if SKIP_MARK in git("log", "--format=%B", f"{base}..HEAD"):
        return []
    since = base[:12] if re.fullmatch(r"[0-9a-f]{40}", base) else base
    return [f"rules/ changed since {since} without an entry in rules/{CHANGELOG}.md "
            f"({', '.join(changed[:5])}{'…' if len(changed) > 5 else ''}). Add a line under "
            f"Unreleased (format at the top of that file), or put {SKIP_MARK} in the commit "
            "message for a typo-only fix."]


def compile_packet(out: Path) -> None:
    """Join the notes in index order into one Markdown file: links become bold text, embeds
    are expanded in place, callouts become bold-titled quotes, headings nest by part."""
    notes, _ = load()
    texts = {name: path.read_text() for name, path in notes.items()}
    emitted: set[str] = set()

    def plain(text: str) -> str:
        def link(m: re.Match[str]) -> str:
            note, heading, alias = m.group(2).strip(), m.group(3), m.group(4)
            return f"**{alias or heading or note}**"

        text = LINK.sub(link, text)
        return re.sub(r"^> \[!\w+\] (.+)$", r"> **\1**\n>", text, flags=re.M)

    def render(name: str, depth: int) -> str:
        emitted.add(name)
        lines = []
        for line in body(texts[name]).splitlines():
            embed = re.fullmatch(r"!\[\[([^\]#|]+)\]\]", line.strip())
            if embed and embed.group(1) in texts:
                lines.append(render(embed.group(1), depth + 1))
                continue
            m = HEADING.match(line)
            if m:
                line = "#" * (len(m.group(1)) + depth) + " " + m.group(2)
            lines.append(line)
        return plain("\n".join(lines)).strip() + "\n"

    index = body(texts[INDEX])
    front, contents = index.split("\n## Contents\n", 1)
    parts = [plain(front).strip() + "\n"]
    for block in re.split(r"^### ", contents, flags=re.M)[1:]:
        title, _, rest = block.partition("\n")
        listed = [t for _, t, _, _ in links(rest) if t in texts and t not in META | {INDEX, FULL}]
        listed = [t for t in listed if t not in emitted]
        if not listed:
            continue
        parts.append(f"# {title.strip()}\n")
        parts += [render(name, 1) for name in listed if name not in emitted]
    out.write_text("\n---\n\n".join(parts))
    print(f"wrote {out} ({len(emitted)} notes)")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--changelog", metavar="BASE", help="git commit to compare HEAD with")
    parser.add_argument("--compile", metavar="OUT", type=Path, help="write the joined packet")
    parser.add_argument("--nav", action="store_true", help="rewrite the reading-order links")
    args = parser.parse_args()
    if args.nav:
        write_nav()
        return
    if args.compile:
        compile_packet(args.compile)
        return
    problems = check_changelog(args.changelog) if args.changelog else check()
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        sys.exit(1)
    print("rules notes OK" if not args.changelog else "changelog OK")


if __name__ == "__main__":
    main()
